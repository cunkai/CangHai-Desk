# -*- coding: utf-8 -*-
"""Generate input-shim-src.js from input-shim.js.

The installers (desktop settings.js, phone phone_adapter.js) need the shim
SOURCE TEXT to inline it into a game's HTML at import time. They cannot
fetch() it: the Canghai pages run on file://, where fetch() is blocked.
So the shim source ships as a plain <script src> string wrapper, loaded by
desktop/index.html and phonehome/index.html like any other shared script:

    window.__CH_INPUT_SHIM_SRC = "<shim source>";

Re-run this script whenever input-shim.js changes. It refuses to emit a
wrapper whose source contains </script or <!-- (either would break the
inlined <script> block in the game's HTML).
"""
import json
import os

HERE = os.path.dirname(os.path.abspath(__file__))
REPO = os.path.dirname(HERE)
SRC = os.path.join(REPO, 'app/src/main/assets/canghai/shared/input-shim.js')
OUT = os.path.join(REPO, 'app/src/main/assets/canghai/shared/input-shim-src.js')


def main():
    src = open(SRC, encoding='utf-8').read()
    assert '</script' not in src.lower(), 'shim contains </script'
    assert '<!--' not in src, 'shim contains <!--'
    assert '__CH_INPUT_SHIM__' in src, 'shim marker missing'
    out = '/* Generated by tools/build_input_shim_src.py — do not edit by hand. */\n'
    out += 'window.__CH_INPUT_SHIM_SRC = ' + json.dumps(src, ensure_ascii=False) + ';\n'
    open(OUT, 'w', encoding='utf-8').write(out)
    print('input-shim-src.js:', len(out), 'bytes from shim', len(src), 'bytes')


if __name__ == '__main__':
    main()
